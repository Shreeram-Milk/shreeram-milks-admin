export const t = translator(notificationMessages)
type Key = keyof typeof notificationMessages.en
const isKey = (key: string): key is Key => key in notificationMessages.en

/** An automatic message's name and when it is sent, in the admin's language. A message the admin does not know keeps the server's words. */
export function eventText(template: { key: string; label: string; trigger: string }): { label: string; trigger: string } {
  const label = `ev_${template.key}`
  const trigger = `evt_${template.key}`
  if (currentLanguage() === 'en' || !isKey(label) || !isKey(trigger)) return { label: template.label, trigger: template.trigger }
  return { label: t(label), trigger: t(trigger) }
}
